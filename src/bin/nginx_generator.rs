//! Generate nginx config for 71 Doors Gallery

use std::fs;

fn main() {
    let config = generate_71_doors_nginx();
    
    fs::write("/tmp/osm-planet-71-doors.nginx", &config)
        .expect("Failed to write nginx config");
    
    println!("✅ Generated: /tmp/osm-planet-71-doors.nginx");
    println!("\nTo deploy:");
    println!("  sudo cp /tmp/osm-planet-71-doors.nginx /etc/nginx/sites-available/osm-planet");
    println!("  sudo ln -sf /etc/nginx/sites-available/osm-planet /etc/nginx/sites-enabled/");
    println!("  sudo nginx -t && sudo systemctl reload nginx");
}

fn generate_71_doors_nginx() -> String {
    let timestamp = chrono::Utc::now();
    
    format!(r#"# OSM Planet - 71 Doors Gallery
# Generated by Rust: {}
# Monster Group [71, 59, 47]

server {{
    listen 443 ssl http2;
    listen [::]:443 ssl http2;

    server_name osm-planet.solfunmeme.com;

    # Nix-built static site
    root /nix/store/PLACEHOLDER-osm-planet-gallery;
    index index.html;

    ssl_certificate /etc/letsencrypt/live/osm-planet.solfunmeme.com/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/osm-planet.solfunmeme.com/privkey.pem;

    # SSL configuration
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_prefer_server_ciphers on;

    # Main gallery
    location / {{
        try_files $uri $uri/ =404;
        add_header X-Monster-Group "71-59-47" always;
        add_header X-Doors "71" always;
    }}

    # 71 Doors
    location /doors/ {{
        try_files $uri $uri/ =404;
        add_header X-Door-Prime "$uri" always;
    }}

    # Door 17 - Hawkins Radiation
    location /doors/door-17.html {{
        try_files $uri =404;
        add_header X-Door "17-Hawkins-Radiation" always;
        add_header X-Cusp "Giza" always;
    }}

    # Door 23 - Consciousness
    location /doors/door-23.html {{
        try_files $uri =404;
        add_header X-Door "23-Consciousness" always;
        add_header X-Cusp "Silicon-Valley" always;
    }}

    # Door 59 - Memory
    location /doors/door-59.html {{
        try_files $uri =404;
        add_header X-Door "59-Memory" always;
        add_header X-Cusp "Ramanujan" always;
    }}

    # Torrent downloads
    location /torrents.html {{
        try_files $uri =404;
        add_header X-Archive "Archive.org" always;
    }}

    # Data API (if needed)
    location /api/ {{
        add_header Content-Type application/json;
        add_header Access-Control-Allow-Origin *;
    }}

    # Health check
    location /health {{
        return 200 "71 Doors Gallery OK\n";
        add_header Content-Type text/plain;
    }}
}}

# HTTP redirect
server {{
    listen 80;
    listen [::]:80;
    server_name osm-planet.solfunmeme.com;
    return 301 https://$server_name$request_uri;
}}
"#, timestamp)
}
